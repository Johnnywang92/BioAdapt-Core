"""Dialect renderers for APP_SCHEMA (plan V2.0 sections 9.7, 11.2)."""

from pathlib import Path

from .schema import APP_SCHEMA, TableSpec

PG_TYPES = {
    "text": "text",
    "int": "bigint",
    "float": "double precision",
    "bool": "boolean",
    "json": "jsonb",
    "timestamp": "timestamptz",
}
SQLITE_TYPES = {
    "text": "text",
    "int": "integer",
    "float": "real",
    "bool": "integer",
    "json": "text",
    "timestamp": "text",
}

#: The session variable the API layer sets with `SET LOCAL app.project_id` per request.
SCOPE_GUC = "app.project_id"
APPEND_ONLY_MESSAGE = "is append-only"
SCOPE_MESSAGE = "row outside the session project scope"
MIGRATION_HEADER = "-- generated by bioadapt_storage.ddl from APP_SCHEMA; do not edit by hand\n"


def _col_defs(table: TableSpec, types: dict[str, str]) -> list[str]:
    lines = []
    for col in table.cols:
        clause = f'  "{col.name}" {types[col.type]}'
        if col.primary_key or not col.nullable:
            clause += " not null"
        lines.append(clause)
    if table.primary_key:
        keys = ", ".join(f'"{name}"' for name in table.primary_key)
        lines.append(f"  primary key ({keys})")
    for group in table.unique_groups:
        cols = ", ".join(f'"{name}"' for name in group)
        lines.append(f"  unique ({cols})")
    return lines


def _index_stmts(table: TableSpec) -> list[str]:
    out = []
    for group in table.indexes:
        cols = ", ".join(f'"{name}"' for name in group)
        out.append(f'create index if not exists "{table.name}_{"_".join(group)}_idx" on "{table.name}" ({cols});')
    for pu in table.partial_unique:
        cols = ", ".join(f'"{name}"' for name in pu.columns)
        out.append(
            f'create unique index if not exists "{table.name}_{pu.where_column}_key" on "{table.name}" ({cols})'
            f" where \"{pu.where_column}\" = '{pu.where_value}';"
        )
    return out


def render_postgres(specs: tuple[TableSpec, ...]) -> str:
    """Production migration: row level security per project, append-only triggers for evidence tables."""
    parts = [
        MIGRATION_HEADER.rstrip("\n"),
        "create or replace function bioadapt_forbid_mutation() returns trigger language plpgsql as $$",
        "begin",
        f"  raise exception '% {APPEND_ONLY_MESSAGE}', tg_table_name;",
        "end;",
        "$$;",
    ]
    for table in specs:
        parts.append(f'create table if not exists "{table.name}" (')
        parts.append(",\n".join(_col_defs(table, PG_TYPES)))
        parts.append(");")
        parts.extend(_index_stmts(table))
        parts.append(f'alter table "{table.name}" enable row level security;')
        parts.append(f'drop policy if exists "{table.name}_project_scope" on "{table.name}";')
        parts.append(
            f'create policy "{table.name}_project_scope" on "{table.name}" as permissive for all\n'
            f"  using (\"project_id\" = current_setting('{SCOPE_GUC}', true))\n"
            f"  with check (\"project_id\" = current_setting('{SCOPE_GUC}', true));"
        )
        if table.append_only:
            parts.append(f'drop trigger if exists "{table.name}_append_only" on "{table.name}";')
            parts.append(
                f'create trigger "{table.name}_append_only" before update or delete on "{table.name}"',
            )
            parts.append("  for each row execute function bioadapt_forbid_mutation();")
    return "\n".join(parts) + "\n"


def render_sqlite(specs: tuple[TableSpec, ...]) -> str:
    """Single-node / test dialect: the project scope is enforced by triggers plus session variable."""
    parts = [MIGRATION_HEADER.rstrip("\n")]
    for table in specs:
        parts.append(f'create table if not exists "{table.name}" (')
        parts.append(",\n".join(_col_defs(table, SQLITE_TYPES)))
        parts.append(");")
        parts.extend(_index_stmts(table))
        if table.append_only:
            # SQLite trigger events are single-valued, so update and delete get their own trigger.
            for event in ("update", "delete"):
                parts.append(
                    f'create trigger if not exists "{table.name}_no_{event}" before {event} on "{table.name}"'
                )
                parts.append(f"begin select raise(abort, '{table.name} {APPEND_ONLY_MESSAGE}'); end;")
        if table.project_scoped:
            parts.append(
                f'create trigger if not exists "{table.name}_insert_scope" before insert on "{table.name}"'
            )
            parts.append(
                f"begin select raise(abort, '{SCOPE_MESSAGE}') "
                f"where new.\"project_id\" <> current_setting('{SCOPE_GUC}', ''); end;"
            )
            parts.append(
                f'create trigger if not exists "{table.name}_update_scope" before update on "{table.name}"'
            )
            parts.append(
                f"begin select raise(abort, '{SCOPE_MESSAGE}') "
                f"where new.\"project_id\" <> old.\"project_id\"; end;"
            )
    return "\n".join(parts) + "\n"


#: The rendered Postgres migration is committed so drift is visible in review.
MIGRATION_NAME = "0001_core.sql"


def write_migration(directory: Path, specs: tuple[TableSpec, ...] = APP_SCHEMA) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / MIGRATION_NAME
    path.write_text(render_postgres(specs), encoding="utf-8")
    return path


def migration_drift(directory: Path, specs: tuple[TableSpec, ...] = APP_SCHEMA) -> bool:
    """True when the committed migration no longer matches APP_SCHEMA."""
    path = directory / MIGRATION_NAME
    return not path.exists() or path.read_text(encoding="utf-8") != render_postgres(specs)
