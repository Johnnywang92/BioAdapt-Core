"""The reference scRNA-seq workflow (plan V2.0 sections 4.1, 7.x, 9.4-9.6).

Exported in three layers, because they are consumed by different people: ``specs`` declares what each
step promises and is what admission reads; ``implementation`` plus ``steps`` are the deterministic
reference executor; ``runner`` drives an orchestrated run against the registry, catalog and journal.
``scanpy_adapter`` is optional and imports no scientific package at module load, so installing this
package on a machine without scanpy is a valid deployment, not a broken one.
"""

